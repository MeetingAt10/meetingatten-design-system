// Generates dist/{tokens.css,tailwind.css,tokens.json,tokens.js,components.css} from tokens/ and src/,
// and inlines assets/icons/sprite.svg into templates/ and preview/ (between <!--ds:sprite--> markers).
import { writeFileSync, mkdirSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadTokens, cssName, cssValue } from './lib.mjs';

const { foundations, themes } = loadTokens();
const dist = join(ROOT, 'dist');
mkdirSync(dist, { recursive: true });
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const banner = `/* @meetingat10/design-system v${pkg.version} - GENERATED by scripts/build.mjs. Do not edit. */\n`;
const entries = (m) => [...m.entries()];
const decl = (n, t) => `  ${cssName(n)}: ${cssValue(t)};`;

// Theme -> selector aliases. accs-landing and accs-admin both resolve to the Figma LIGHT mode.
const THEMES = {
  'accs-light': { aliases: ['accs-light', 'accs-landing', 'accs-admin'], root: true, legacy: true },
  'accs-dark': { aliases: ['accs-dark', 'accs-admin-dark'], legacy: true },
  meetingatten: { aliases: ['meetingatten'] },
  'meetingatten-dark': { aliases: ['meetingatten-dark'] },
};
const SELECTABLE = ['accs-landing', 'accs-admin', 'accs-admin-dark', 'meetingatten', 'meetingatten-dark'];
const LEGACY = { // per-repo --accs-* names (accs-landing, accs-system globals.css) -> Figma semantic tokens
  '--accs-canvas': 'canvas', '--accs-surface': 'surface', '--accs-text-primary': 'text-primary', '--accs-text-secondary': 'text-secondary',
  '--accs-border-subtle': 'border-subtle', '--accs-action': 'action-default', '--accs-action-hover': 'action-hover', '--accs-on-action': 'on-action',
  '--accs-focus': 'focus', '--accs-info-bg': 'info-bg', '--accs-secondary-bg': 'secondary-bg', '--accs-secondary-fg': 'secondary-fg',
  '--accs-accent-bg': 'accent-bg', '--accs-accent-fg': 'accent-fg', '--accs-radius-card': 'radius-8',
  '--accs-font-display': 'font-family-display', '--accs-font-body': 'font-family-body',
};

// ---- tokens.css ----
let css = banner + `/* Primitives and foundations (theme independent). Use semantic tokens below in product code. */\n:root {\n`;
css += entries(foundations).map(([n, t]) => decl(n, t)).join('\n') + '\n}\n';
for (const [name, cfg] of Object.entries(THEMES)) {
  const th = themes[name];
  const sel = cfg.aliases.flatMap((a) => [`[data-theme="${a}"]`, `.theme-${a}`]);
  if (cfg.root) sel.unshift(':root');
  css += `\n/* ${name}: ${th.description} */\n${sel.join(',\n')} {\n  color-scheme: ${th.dark ? 'dark' : 'light'};\n`;
  css += entries(th.tokens).map(([n, t]) => decl(n, t)).join('\n') + '\n';
  if (cfg.legacy) css += '  /* legacy --accs-* aliases */\n' + Object.entries(LEGACY).map(([k, v]) => `  ${k}: var(--ds-${v});`).join('\n') + '\n';
  css += '}\n';
}
writeFileSync(join(dist, 'tokens.css'), css);

// ---- tailwind.css (Tailwind 4) ----
const v = (n) => `var(${cssName(n)})`;
const light = themes['accs-light'].tokens;
let tw = banner + `@import "./tokens.css";\n\n/* Literal values: breakpoints cannot use var(); spacing keeps Tailwind's 4px multiplier (p-4 = Figma space/16). */\n@theme {\n  --spacing: 0.25rem;\n  --breakpoint-*: initial;\n`;
tw += entries(foundations).filter(([n]) => n.startsWith('breakpoint.')).map(([n, t]) => `  --breakpoint-${n.split('.')[1]}: ${t.value};`).join('\n');
tw += `\n  --container-content: 75rem;\n  --container-reading: 42.5rem;\n  --container-sidebar: 15rem;\n}\n\n@theme inline {\n`;
const L = [];
const color = (n) => { const p = n.split('.').slice(1); L.push(`--color-${p.join('-')}: ${v(n)};`); if (p.at(-1) === 'default') L.push(`--color-${p.slice(0, -1).join('-')}: ${v(n)};`); };
for (const [n] of foundations) if (n.startsWith('color.')) color(n);
for (const [n] of light) color(n);
L.push(`--color-ink: var(--ds-text-primary);`, `--color-ink-secondary: var(--ds-text-secondary);`, `--color-line: var(--ds-border-subtle);`);
L.push(`--font-display: var(--ds-font-family-display);`, `--font-sans: var(--ds-font-family-body);`, `--font-mono: var(--ds-font-family-mono);`);
L.push(`--font-weight-regular: 400;`, `--font-weight-medium: 500;`, `--font-weight-semibold: 600;`, `--font-weight-bold: 700;`);
const types = [...new Set(entries(foundations).filter(([n]) => n.startsWith('type.')).map(([n]) => n.split('.')[1]))];
for (const k of types) L.push(`--text-${k}: var(--ds-type-${k}-size);`, `--text-${k}--line-height: var(--ds-type-${k}-line-height);`);
L.push(`--radius-chip: var(--ds-radius-4);`, `--radius-control: var(--ds-radius-6);`, `--radius-card: var(--ds-radius-8);`, `--radius-overlay: var(--ds-radius-12);`);
L.push(`--shadow-raised: var(--ds-shadow-elevation-1);`, `--shadow-overlay: var(--ds-shadow-elevation-2);`);
L.push(`--ease-standard: var(--ds-motion-ease-standard);`, `--default-transition-duration: var(--ds-motion-duration-fast);`, `--default-transition-timing-function: var(--ds-motion-ease-standard);`);
tw += L.map((l) => '  ' + l).join('\n') + '\n}\n\n/* Full Figma text styles: class="type-h1" sets family, weight, size, line-height and tracking together. */\n';
for (const k of types) tw += `@utility type-${k} {\n  font-family: var(--ds-type-${k}-font-family);\n  font-weight: var(--ds-type-${k}-font-weight);\n  font-size: var(--ds-type-${k}-size);\n  line-height: var(--ds-type-${k}-line-height);\n  letter-spacing: var(--ds-type-${k}-letter-spacing);\n}\n`;
tw += `\n/* Strict palette (drops Tailwind's default colors): add "@theme { --color-*: initial; }" before importing this file. */\n`;
writeFileSync(join(dist, 'tailwind.css'), tw);

// ---- tokens.json / tokens.js ----
const toObj = (m) => Object.fromEntries(entries(m).map(([n, t]) => [n, { $type: t.type, $value: t.value, ...(t.alias ? { $alias: `{${t.alias}}` } : {}), cssVar: cssName(n) }]));
writeFileSync(join(dist, 'tokens.json'), JSON.stringify({ name: pkg.name, version: pkg.version, foundations: toObj(foundations),
  themes: Object.fromEntries(Object.entries(themes).map(([n, t]) => [n, { dark: t.dark, description: t.description, aliases: THEMES[n].aliases, tokens: toObj(t.tokens) }])) }, null, 2) + '\n');
const flat = { foundations: entries(foundations).map(([n, t]) => ({ name: n, type: t.type, css: cssName(n), value: cssValue(t) })),
  semantic: entries(light).map(([n]) => ({ name: n, css: cssName(n) })), selectable: SELECTABLE,
  values: Object.fromEntries(Object.keys(themes).map((k) => [k, Object.fromEntries(entries(themes[k].tokens).map(([n, t]) => [n.replace(/^color\./, ''), t.value]))])),
  themes: Object.fromEntries(SELECTABLE.map((a) => { const k = Object.keys(THEMES).find((x) => THEMES[x].aliases.includes(a)); return [a, { source: k, description: themes[k].description }]; })) };
writeFileSync(join(dist, 'tokens.js'), banner + `window.DS_TOKENS = ${JSON.stringify(flat)};\n`);

// ---- components.css ----
writeFileSync(join(dist, 'components.css'), banner + readFileSync(join(ROOT, 'src/components.css'), 'utf8'));

// ---- inline icon sprite into static pages ----
const sprite = readFileSync(join(ROOT, 'assets/icons/sprite.svg'), 'utf8').replace(/<!--[\s\S]*?-->/g, '').replace(/^<svg[^>]*>|<\/svg>\s*$/g, '').trim();
const block = `<!--ds:sprite--><svg width="0" height="0" style="position:absolute" aria-hidden="true" fill="none" stroke="currentColor" stroke-linecap="round" stroke-linejoin="round">${sprite}</svg><!--/ds:sprite-->`;
for (const dir of ['templates', 'preview']) for (const f of readdirSync(join(ROOT, dir)).filter((x) => x.endsWith('.html'))) {
  const p = join(ROOT, dir, f), h = readFileSync(p, 'utf8');
  const n = h.replace(/<!--ds:sprite-->[\s\S]*?<!--\/ds:sprite-->/, () => block);
  if (n !== h) writeFileSync(p, n);
}
console.log(`built dist/ - ${foundations.size} foundation tokens; themes: ${Object.keys(themes).join(', ')} (${light.size} semantic tokens each)`);
