// Generates, from tokens/ and src/css/:
//   dist/tokens.css, dist/tailwind.css, dist/tokens.json, dist/tokens.js, dist/fonts.css, dist/components.css,
//   assets/icons/sprite.svg, src/react/icon/icons.ts and src/react/lib/motion.ts.
import { writeFileSync, mkdirSync, readFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadTokens, loadTreatments, treatmentCss, cssName, cssValue, springCurve } from './lib.mjs';

const { foundations, themes } = loadTokens();
const TR = Object.entries(loadTreatments());
const dist = join(ROOT, 'dist');
mkdirSync(dist, { recursive: true });
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const banner = `/* @meetingat10/design-system v${pkg.version} - GENERATED by scripts/build.mjs. Do not edit. */\n`;
const tsBanner = `// GENERATED by scripts/build.mjs. Do not edit.\n`;
const entries = (m) => [...m.entries()];

// A spring token becomes two properties: the linear() curve and the duration it needs to settle.
const decl = (n, t) => {
  // Type styles point at the family tokens, so an app can swap a family once (for example next/font variables).
  if (t.type === 'fontFamily' && t.alias) return `  ${cssName(n)}: var(${cssName(t.alias)});`;
  if (t.type !== 'spring') return `  ${cssName(n)}: ${cssValue(t)};`;
  const s = springCurve(t.value);
  return `  ${cssName(n)}: ${s.linear};\n  ${cssName(n)}-duration: ${s.duration}ms;`;
};

// Theme file -> data-theme value. Light is the :root default; no data-theme follows prefers-color-scheme.
const THEMES = { 'accs-light': 'light', 'accs-dark': 'dark' };
const SELECTABLE = Object.values(THEMES);
// data-density: [text style, section space, section space from 1024px]. Comfortable is the default.
const DENSITY = { comfortable: ['body', 64, 96], compact: ['body-small', 24, 32] };

// ---- tokens.css ----
let css = banner + `/* Primitives and foundations (theme independent). Product code uses the semantic tokens below. */\n:root {\n`;
css += entries(foundations).map(([n, t]) => decl(n, t)).join('\n') + '\n';
css += '}\n';
// Every treatment is declared inside each theme block: a custom property that references a theme token resolves
// where it is declared, so a :root declaration would freeze the light value for dark subtrees.
const themeBody = (th, pad) => `${pad}color-scheme: ${th.dark ? 'dark' : 'light'};\n` + entries(th.tokens).map(([n, t]) => pad + decl(n, t).trim()).join('\n') + '\n'
  + `${pad}/* treatments */\n` + TR.map(([k, v]) => `${pad}--ds-${k}: ${treatmentCss(th.dark ? v.dark : v.light)};`).join('\n') + '\n';
for (const [file, name] of Object.entries(THEMES)) {
  const th = themes[file];
  css += `\n/* ${name}: ${th.description} */\n${name === 'light' ? ':root,\n' : ''}[data-theme="${name}"] {\n${themeBody(th, '  ')}}\n`;
}
css += `\n/* No data-theme: follow the OS setting. */\n@media (prefers-color-scheme: dark) {\n  :root:not([data-theme]) {\n${themeBody(themes['accs-dark'], '    ')}  }\n}\n`;
for (const [d, [text, sec, secWide]] of Object.entries(DENSITY)) {
  css += `\n/* density: ${d} */\n${d === 'comfortable' ? ':root,\n' : ''}[data-density="${d}"] {\n`;
  css += ['font-family', 'font-weight', 'size', 'line-height', 'letter-spacing'].map((k) => `  --ds-density-text-${k}: var(--ds-type-${text}-${k});`).join('\n');
  css += `\n  --ds-density-section-space: var(--ds-space-${sec});\n  --ds-density-section-space-desktop: var(--ds-space-${secWide});\n`;
  css += `  --ds-density-hour-row: var(--ds-size-hour-row${d === 'compact' ? '-compact' : ''});\n}\n`;
}
writeFileSync(join(dist, 'tokens.css'), css);

// ---- fonts.css: self-hosted pinned families (optional; next/font apps map their own variables instead) ----
writeFileSync(join(dist, 'fonts.css'), banner + `/* Variable Inter, Plus Jakarta Sans and JetBrains Mono from fontsource. The token font stacks name these families first. */
@import "@fontsource-variable/inter/wght.css";
@import "@fontsource-variable/plus-jakarta-sans/wght.css";
@import "@fontsource-variable/jetbrains-mono/wght.css";
`);

// ---- tailwind.css (Tailwind 4) ----
const v = (n) => `var(${cssName(n)})`;
const light = themes['accs-light'].tokens;
let tw = banner + `@import "./tokens.css";\n\n/* Literal values: breakpoints cannot use var(); spacing keeps Tailwind's 4px multiplier (p-4 = space/16). */\n@theme {\n  --color-*: initial;\n  --spacing: 0.25rem;\n  --breakpoint-*: initial;\n`;
tw += entries(foundations).filter(([n]) => n.startsWith('breakpoint.')).map(([n, t]) => `  --breakpoint-${n.split('.')[1]}: ${t.value};`).join('\n');
tw += `\n  --container-content: 80rem;\n  --container-reading: 42.5rem;\n  --container-sidebar: 16rem;\n}\n\n@theme inline {\n`;
const L = [];
const color = (n) => { const p = n.split('.').slice(1); L.push(`--color-${p.join('-')}: ${v(n)};`); if (p.at(-1) === 'default') L.push(`--color-${p.slice(0, -1).join('-')}: ${v(n)};`); };
for (const [n] of light) color(n); // semantic only: primitives stay internal to the design system
for (const [k] of TR) if (k.startsWith('highlight-')) L.push(`--color-${k}: var(--ds-${k});`);
L.push(`--font-display: var(--ds-font-family-display);`, `--font-sans: var(--ds-font-family-body);`, `--font-mono: var(--ds-font-family-mono);`);
L.push(`--font-weight-regular: 400;`, `--font-weight-medium: 500;`, `--font-weight-semibold: 600;`, `--font-weight-bold: 700;`, `--font-weight-extrabold: 800;`);
const types = [...new Set(entries(foundations).filter(([n]) => n.startsWith('type.')).map(([n]) => n.split('.')[1]))];
for (const k of types) L.push(`--text-${k}: var(--ds-type-${k}-size);`, `--text-${k}--line-height: var(--ds-type-${k}-line-height);`);
for (const k of ['sheet', 'block', 'control', 'chip', 'overlay', 'plate']) L.push(`--radius-${k}: var(--ds-radius-${k});`);
L.push(`--shadow-block: var(--ds-block-shadow);`, `--shadow-overlay: var(--ds-overlay-shadow);`);
L.push(`--ease-out: var(--ds-motion-ease-out);`, `--ease-in-out: var(--ds-motion-ease-in-out);`, `--ease-spring: var(--ds-motion-spring-smooth);`);
L.push(`--default-transition-duration: var(--ds-motion-duration-quick);`, `--default-transition-timing-function: var(--ds-motion-ease-out);`);
tw += L.map((l) => '  ' + l).join('\n') + '\n}\n\n/* Whole text styles: class="type-h1" sets family, weight, size, line-height and tracking together. */\n';
for (const k of types) tw += `@utility type-${k} {\n  font-family: var(--ds-type-${k}-font-family);\n  font-weight: var(--ds-type-${k}-font-weight);\n  font-size: var(--ds-type-${k}-size);\n  line-height: var(--ds-type-${k}-line-height);\n  letter-spacing: var(--ds-type-${k}-letter-spacing);\n}\n`;
tw += `\n/* Materials: hatching for taken or restricted areas, the door plate. */\n@utility hatch {\n  background-image: var(--ds-hatch);\n}\n@utility hatch-strong {\n  background-image: var(--ds-hatch-strong);\n}\n@utility plate {\n  background: var(--ds-plate-bg);\n  color: var(--ds-plate-fg);\n  border-radius: var(--ds-radius-plate);\n}\n`;
writeFileSync(join(dist, 'tailwind.css'), tw);

// ---- tokens.json / tokens.js ----
const toObj = (m) => Object.fromEntries(entries(m).map(([n, t]) => [n, { $type: t.type, $value: t.value, ...(t.alias ? { $alias: `{${t.alias}}` } : {}), cssVar: cssName(n) }]));
writeFileSync(join(dist, 'tokens.json'), JSON.stringify({ name: pkg.name, version: pkg.version, foundations: toObj(foundations), treatments: Object.fromEntries(TR),
  themes: Object.fromEntries(Object.entries(themes).map(([n, t]) => [THEMES[n], { dark: t.dark, description: t.description, source: n, tokens: toObj(t.tokens) }])) }, null, 2) + '\n');
const flat = { foundations: entries(foundations).map(([n, t]) => ({ name: n, type: t.type, css: cssName(n), value: cssValue(t) })),
  semantic: entries(light).map(([n]) => ({ name: n, css: cssName(n) })), selectable: SELECTABLE,
  values: Object.fromEntries(Object.keys(themes).map((k) => [THEMES[k], Object.fromEntries(entries(themes[k].tokens).map(([n, t]) => [n.replace(/^color\./, ''), t.value]))])),
  themes: Object.fromEntries(Object.entries(THEMES).map(([k, a]) => [a, { source: k, description: themes[k].description }])) };
writeFileSync(join(dist, 'tokens.js'), banner + `window.DS_TOKENS = ${JSON.stringify(flat)};\n`);

// ---- components.css: src/css/** in cascade order, inside ds.* layers (unlayered app CSS wins; Tailwind apps declare `ds` before `components, utilities`) ----
const LAYERS = {
  'ds.base': ['base/reset', 'base/type', 'base/layout', 'base/motion'],
  'ds.components': [
    'icon/icon', 'feedback/spinner',
    'control/button', 'control/icon-button', 'control/field', 'control/input', 'control/listbox', 'control/select', 'control/combobox', 'control/checkbox', 'control/radio', 'control/switch',
    'control/segmented', 'control/tag', 'control/kbd', 'control/calendar', 'control/date-picker', 'control/file-upload',
    'badge/badge',
    'navigation/link', 'navigation/nav-item', 'navigation/tabs', 'navigation/sidebar', 'navigation/top-bar', 'navigation/mobile-header', 'navigation/app-shell', 'navigation/navbar',
    'navigation/breadcrumbs', 'navigation/pagination', 'navigation/stepper', 'navigation/menu', 'navigation/footer', 'navigation/command',
    'content/card', 'content/tile', 'content/avatar',
    'scheduling/time-block', 'scheduling/now-line', 'scheduling/timetable', 'scheduling/slot-picker',
    'data/table', 'data/report-record', 'data/case-timeline', 'data/skeleton', 'data/view-state',
    'feedback/alert', 'feedback/toast', 'feedback/modal', 'feedback/drawer', 'feedback/tooltip', 'feedback/popover', 'feedback/empty-state',
    'feedback/progress', 'feedback/meter', 'feedback/privacy-notice', 'feedback/disclosure',
    'layout/divider', 'layout/section', 'layout/section-header', 'layout/hero', 'layout/agenda', 'layout/highlight',
    'identity/door-plate', 'identity/logo',
  ].map((f) => 'components/' + f),
  'ds.utilities': ['base/utilities', 'base/forced-colors'],
};
const listed = Object.values(LAYERS).flat();
const onDisk = readdirSync(join(ROOT, 'src/css'), { recursive: true }).filter((f) => f.endsWith('.css')).map((f) => f.replace(/\.css$/, ''));
const unlisted = onDisk.filter((f) => !listed.includes(f));
const missing = listed.filter((f) => !onDisk.includes(f));
if (unlisted.length) throw new Error('Add to LAYERS in scripts/build.mjs: ' + unlisted.join(', '));
if (missing.length) throw new Error('Listed in LAYERS but missing from src/css: ' + missing.join(', '));
let comp = banner + `/* Components. Token-only. Forced-state classes (.is-hover, .is-pressed, .is-focus, .is-error) exist for static state matrices;
   React Aria state attributes ([data-hovered], [data-pressed], [data-focus-visible], [data-disabled]) are matched alongside native states. */
@layer ${Object.keys(LAYERS).join(', ')};\n`;
for (const [layer, files] of Object.entries(LAYERS))
  comp += `\n@layer ${layer} {\n` + files.map((f) => `/* src/css/${f}.css */\n` + readFileSync(join(ROOT, 'src/css', f + '.css'), 'utf8').trim()).join('\n\n') + '\n}\n';
writeFileSync(join(dist, 'components.css'), comp);

// ---- icons: curated Phosphor vocabulary -> sprite (plain CSS layer) and the React name map ----
const { icons } = JSON.parse(readFileSync(join(ROOT, 'assets/icons/icons.json'), 'utf8'));
const core = join(ROOT, 'node_modules/@phosphor-icons/core/assets');
const WEIGHTS = { regular: '', fill: '-fill', duotone: '-duotone' };
const inner = (svg) => svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').trim();
let sprite = `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true" style="display:none">\n<!-- GENERATED by scripts/build.mjs from assets/icons/icons.json (Phosphor Icons, MIT). <use href="sprite.svg#ds-NAME">, #ds-NAME-fill, #ds-NAME-duotone. -->\n`;
for (const [name, file] of Object.entries(icons))
  for (const [weight, suffix] of Object.entries(WEIGHTS)) {
    const svg = readFileSync(join(core, weight, `${file}${suffix}.svg`), 'utf8');
    sprite += `<symbol id="ds-${name}${suffix}" viewBox="0 0 256 256" fill="currentColor">${inner(svg)}</symbol>\n`;
  }
writeFileSync(join(ROOT, 'assets/icons/sprite.svg'), sprite + '</svg>\n');
const pascal = (f) => f.split('-').map((p) => p[0].toUpperCase() + p.slice(1)).join('') + 'Icon';
const iconImports = [...new Set(Object.values(icons).map(pascal))].sort();
writeFileSync(join(ROOT, 'src/react/icon/icons.ts'), tsBanner + `// Curated icon vocabulary from assets/icons/icons.json (Phosphor Icons). Any other Phosphor icon: '@meetingat10/design-system/icons'.
// The ssr entry renders without React context, so <Icon> also works inside React Server Components.
import {\n${iconImports.map((i) => `  ${i},`).join('\n')}\n} from '@phosphor-icons/react/ssr';
import type { Icon as PhosphorIcon } from '@phosphor-icons/react';

export const ICONS = {\n${Object.entries(icons).map(([n, f]) => `  ${JSON.stringify(n)}: ${pascal(f)},`).join('\n')}\n} satisfies Record<string, PhosphorIcon>;

export type IconName = keyof typeof ICONS;
`);

// ---- motion: the same durations, eases, springs and distances for Motion (seconds, arrays, spring configs) ----
const motion = (kind) => entries(foundations).filter(([n]) => n.startsWith(`motion.${kind}.`)).map(([n, t]) => [n.split('.')[2], t.value]);
const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());
const springs = motion('spring').map(([k, s]) => `  ${camel(k)}: { type: 'spring', stiffness: ${s.stiffness}, damping: ${s.damping}, mass: ${s.mass ?? 1} },`);
writeFileSync(join(ROOT, 'src/react/lib/motion.ts'), tsBanner + `// Motion tokens from tokens/foundations/motion.json, shaped for the motion library (durations in seconds).
export const duration = {\n${motion('duration').map(([k, d]) => `  ${camel(k)}: ${parseFloat(d) / 1000},`).join('\n')}\n} as const;

export const ease = {\n${motion('ease').map(([k, e]) => `  ${camel(k)}: [${e.join(', ')}] as [number, number, number, number],`).join('\n')}\n} as const;

export const spring = {\n${springs.join('\n')}\n} as const;

export const distance = {\n${motion('distance').map(([k, d]) => `  ${camel(k)}: ${parseFloat(d)},`).join('\n')}\n} as const;
`);

console.log(`built dist/ - ${foundations.size} foundation tokens; themes: ${Object.keys(themes).join(', ')} (${light.size} semantic tokens each); ${Object.keys(icons).length} icons x 3 weights`);
