// Generates dist/{tokens.css,tailwind.css,tokens.json,tokens.js,components.css} from tokens/ and src/.
import { writeFileSync, mkdirSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { ROOT, loadTokens, cssName, cssValue } from './lib.mjs';

const { foundations, themes } = loadTokens();
const dist = join(ROOT, 'dist');
mkdirSync(dist, { recursive: true });
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
const banner = `/* @meetingat10/design-system v${pkg.version} - GENERATED by scripts/build.mjs. Do not edit. */\n`;

const decl = (name, t) => `  ${cssName(name)}: ${cssValue(t)};`;
const entries = (m) => [...m.entries()];

// ---- tokens.css ----
const DEFAULT_THEME = 'accs-landing';
const LEGACY = { // old per-repo --accs-* names -> new semantic tokens (drop-in compatibility)
  '--accs-canvas': 'canvas', '--accs-surface': 'surface', '--accs-text-primary': 'ink', '--accs-text-secondary': 'ink-secondary',
  '--accs-border-subtle': 'line', '--accs-action': 'action', '--accs-action-hover': 'action-hover', '--accs-on-action': 'on-action',
  '--accs-focus': 'focus', '--accs-info-bg': 'info-bg', '--accs-secondary-bg': 'accent-bg', '--accs-secondary-fg': 'accent-fg',
  '--accs-accent-bg': 'accent-bg', '--accs-accent-fg': 'accent-fg', '--accs-radius-card': 'radius-card',
  '--accs-font-display': 'font-family-display', '--accs-font-body': 'font-family-body',
};
let css = banner + `/* Primitives and foundations (theme independent). Prefer semantic tokens below in product code. */\n:root {\n`;
css += entries(foundations).map(([n, t]) => decl(n, t)).join('\n') + '\n}\n';
for (const [name, th] of Object.entries(themes)) {
  const sel = [`[data-theme="${name}"]`, `.theme-${name}`];
  if (name === DEFAULT_THEME) sel.unshift(':root');
  css += `\n/* Theme: ${name} - ${th.description} */\n${sel.join(',\n')} {\n  color-scheme: ${th.dark ? 'dark' : 'light'};\n`;
  css += entries(th.tokens).map(([n, t]) => decl(n, t)).join('\n') + '\n';
  css += '  /* legacy --accs-* aliases (resolved per theme) */\n';
  css += Object.entries(LEGACY).map(([k, v]) => `  ${k}: var(--ds-${v});`).join('\n') + '\n}\n';
}
writeFileSync(join(dist, 'tokens.css'), css);

// ---- tailwind.css (Tailwind 4) ----
const base = themes[DEFAULT_THEME].tokens;
const v = (n) => `var(${cssName(n)})`;
let tw = banner + `@import "./tokens.css";\n\n/* Literal values: media queries and the spacing base cannot use var(). */\n@theme {\n`;
tw += `  --spacing: 0.25rem;\n` + entries(foundations).filter(([n]) => n.startsWith('breakpoint.')).map(([n, t]) => `  --breakpoint-${n.split('.')[1]}: ${t.value};`).join('\n') + '\n}\n\n';
tw += `/* Everything else resolves through CSS variables so [data-theme] switches work at runtime. */\n@theme inline {\n`;
const L = [];
for (const [n] of foundations) {
  const p = n.split('.');
  if (p[0] === 'color') L.push(`--color-${p.slice(1).join('-')}: ${v(n)};`);
  if (p[0] === 'font' && p[1] === 'family') L.push(`--font-${p[2] === 'body' ? 'sans' : p[2]}: ${v(n)};`);
  if (p[0] === 'font' && p[1] === 'weight') L.push(`--font-weight-${p[2]}: ${v(n)};`);
  if (p[0] === 'text') L.push(p[2] === 'size' ? `--text-${p[1]}: ${v(n)};` : `--text-${p[1]}--${p[2] === 'tracking' ? 'letter-spacing' : 'line-height'}: ${v(n)};`);
  if (p[0] === 'radius') L.push(`--radius-${p[1]}: ${v(n)};`);
  if (p[0] === 'shadow') L.push(`--shadow-${p[1]}: ${v(n)};`);
  if (p[0] === 'motion' && p[1] === 'ease') L.push(`--ease-${p[2]}: ${v(n)};`);
}
for (const [n] of base) {
  const k = n.replace(/^(color|size)\./, '');
  if (n.startsWith('color.')) L.push(`--color-${k}: ${v(n)};`);
  else if (k.startsWith('radius-')) L.push(`--${k}: ${v(n)};`);
}
L.push(`--default-transition-duration: ${v('motion.duration.base')};`, `--default-transition-timing-function: ${v('motion.ease.standard')};`);
tw += L.map((l) => '  ' + l).join('\n') + '\n}\n\n';
tw += `/* Opt in to strict palettes by adding "@theme { --color-*: initial; }" before this file's theme blocks. */\n`;
writeFileSync(join(dist, 'tailwind.css'), tw);

// ---- tokens.json / tokens.js ----
const toObj = (m) => Object.fromEntries(entries(m).map(([n, t]) => [n, { $type: t.type, $value: t.value, cssVar: cssName(n) }]));
const json = { name: pkg.name, version: pkg.version, foundations: toObj(foundations),
  themes: Object.fromEntries(Object.entries(themes).map(([n, t]) => [n, { dark: t.dark, description: t.description, tokens: toObj(t.tokens) }])) };
writeFileSync(join(dist, 'tokens.json'), JSON.stringify(json, null, 2) + '\n');
const flat = { foundations: entries(foundations).map(([n, t]) => ({ name: n, type: t.type, css: cssName(n), value: cssValue(t) })),
  semantic: entries(themes[DEFAULT_THEME].tokens).map(([n, t]) => ({ name: n, type: t.type, css: cssName(n) })),
  themes: Object.fromEntries(Object.entries(themes).map(([n, t]) => [n, t.description])) };
writeFileSync(join(dist, 'tokens.js'), banner + `window.DS_TOKENS = ${JSON.stringify(flat)};\n`);

// ---- components.css (hand-written in src/, token-only) ----
writeFileSync(join(dist, 'components.css'), banner + readFileSync(join(ROOT, 'src/components.css'), 'utf8'));
console.log(`built dist/ - ${foundations.size} foundation tokens, ${Object.keys(themes).length} themes x ${base.size} semantic tokens`);
